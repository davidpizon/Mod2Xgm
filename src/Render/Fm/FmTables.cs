    /// <summary>Extracts <paramref name="length"/> bits of <paramref name="value"/> starting at bit <paramref name="start"/>.</summary>
    public static uint Bitfield(uint value, int start, int length = 1) => (value >> start) & ((1u << length) - 1);

    /// <summary>Limits <paramref name="value"/> to <paramref name="min"/>…<paramref name="max"/>.</summary>
    public static int Clamp(int value, int min, int max) => value < min ? min : value > max ? max : value;

    /// <summary>Converts a 5.8 logarithmic attenuation to a 13-bit linear volume.</summary>
    public static uint AttenuationToVolume(uint input) => (uint)(PowerTable[input & 0xff] >> (int)(input >> 8));

    /// <summary>
    /// The 4-bit envelope increment for a 6-bit <paramref name="rate"/> at step <paramref name="index"/> (0–7) of the
    /// envelope counter; for the attack, the fractional factor the attenuation shrinks by.
    /// </summary>
    public static uint AttenuationIncrement(uint rate, uint index) => Bitfield(IncrementTable[(int)rate], 4 * (int)index, 4);

    /// <summary>The signed phase displacement for a 3-bit <paramref name="detune"/> at a 5-bit <paramref name="keycode"/>.</summary>
    public static int DetuneAdjustment(uint detune, uint keycode)
    {
        int result = DetuneTable[(int)((keycode * 4) + (detune & 3))];
        return Bitfield(detune, 2) != 0 ? -result : result;
    }

    /// <summary>
    /// The LFO's vibrato as a signed F-number adjustment, from the top 7 F-number bits, the channel's PM depth (0–7) and
    /// the LFO's signed 5-bit PM value; written in ymfm to match Nuked-OPN2.
    /// </summary>
    public static int LfoPmPhaseAdjustment(uint fnumBits, uint pmSensitivity, int lfoRawPm)
    {
        int absPm = lfoRawPm < 0 ? -lfoRawPm : lfoRawPm;
        uint shifts = LfoPmShifts[(int)((pmSensitivity * 8) + Bitfield((uint)absPm, 0, 3))];
        int adjust = (int)((fnumBits >> (int)Bitfield(shifts, 0, 4)) + (fnumBits >> (int)Bitfield(shifts, 4, 4)));
        if (pmSensitivity > 5)
        {
            adjust <<= (int)(pmSensitivity - 5);
        }

        adjust >>= 2;
        return lfoRawPm < 0 ? -adjust : adjust;
    }

    /// <summary>|sin| of a 10-bit phase as attenuation: the second half of each quarter mirrors the first.</summary>
    private static uint AbsSinAttenuation(uint input)
    {
        if (Bitfield(input, 8) != 0)
        {
            input = ~input;
        }

        return SinTable[(int)(input & 0xff)];
    }

    private static ushort[] BuildWaveform()
    {
        ushort[] waveform = new ushort[WaveformLength];
        for (uint index = 0; index < WaveformLength; index++)
        {
            waveform[index] = (ushort)(AbsSinAttenuation(index) | (Bitfield(index, 9) << 15));
        }

        return waveform;
    }

    private static ushort[] BuildPowerTable()
    {
        ReadOnlySpan<ushort> mantissas = PowerMantissas;
        ushort[] table = new ushort[mantissas.Length];
        for (int i = 0; i < table.Length; i++)
        {
            table[i] = (ushort)((mantissas[i] | 0x400) << 2);
        }

        return table;
    }
